"""Checkpoint-safe research state.

The checkpointer stores this dict. It must stay JSON: no clients, sessions,
raw pages, or embedding vectors. Nodes replace fields; they do not mutate
the lists on the state they were given.
"""

import asyncio
import json
import math
from collections.abc import Awaitable, Callable, Mapping
from datetime import datetime
from typing import Literal, TypedDict, cast
from uuid import UUID

from pydantic import ValidationError

from nexus.schemas.report import GraphUsage, ResearchReport
from nexus.schemas.research import QUERY_MAX_LENGTH, ResearchPlan
from nexus.tools.web_search import normalize_url

STATE_SCHEMA_VERSION = 1
MAX_STORED_EXCERPT = 2000
_MAX_QUESTION = 2000
_MAX_TITLE = 200
_MAX_WARNING = 64
_MAX_WARNINGS = 32
_MAX_CANDIDATES = 50
_MAX_BATCHES = 2
_MAX_QUERIES_PER_BATCH = 3
_MAX_EVIDENCE = 50
_MAX_COVERAGE_TEXT = 500
_MAX_TASK_IDS = 3

RunStatus = Literal[
    "running",
    "completed",
    "partial",
    "insufficient_evidence",
    "failed",
    "interrupted",
]
_REPORT_STATUSES = {"completed", "partial", "insufficient_evidence"}
_FAILURE_STATUSES = {"failed", "interrupted"}
_STATE_KEYS = (
    "schema_version",
    "research_id",
    "run_id",
    "question",
    "plan",
    "query_batches",
    "candidate_urls",
    "accepted_source_ids",
    "accepted_urls",
    "rejected_urls",
    "evidence",
    "coverage",
    "iteration",
    "usage",
    "warnings",
    "status",
    "report",
    "error_code",
    "started_at",
    "iteration_progress",
)


class GraphStateError(ValueError):
    """State cannot be checkpointed or routed."""


class UsageSnapshot(TypedDict):
    """Logical provider counts. One discovery call is not one search."""

    search_calls: int
    llm_calls: int
    pages_indexed: int
    pages_failed: int
    evaluation_calls: int
    synthesis_calls: int


class CandidateUrl(TypedDict):
    """A normalized URL waiting to be indexed. Snippets are not stored."""

    url: str
    title: str


class EvidenceState(TypedDict):
    """A selected passage. The excerpt is capped before it is stored."""

    chunk_id: str
    source_id: str
    research_id: str
    url: str | None
    page_number: int | None
    score: float
    excerpt: str


class CoverageState(TypedDict):
    """Evaluator advice. Routing may ignore the sufficiency flag."""

    sufficient: bool
    covered_task_ids: list[str]
    missing_task_ids: list[str]
    gaps: list[str]
    uncertainty: str


class ProgressSnapshot(TypedDict):
    """Counts at the start of the current iteration, used to detect progress."""

    pages_indexed: int
    chunk_ids: list[str]


class ResearchState(TypedDict):
    """One run. ``research_id`` scopes evidence; ``run_id`` is the thread id."""

    schema_version: int
    research_id: str
    run_id: str
    question: str
    plan: dict[str, object] | None
    query_batches: list[list[str]]
    candidate_urls: list[CandidateUrl]
    accepted_source_ids: list[str]
    accepted_urls: list[str]
    rejected_urls: list[str]
    evidence: list[EvidenceState]
    coverage: CoverageState | None
    iteration: int
    usage: UsageSnapshot
    warnings: list[str]
    status: RunStatus
    report: dict[str, object] | None
    error_code: str | None
    started_at: str
    iteration_progress: ProgressSnapshot


def initial_state(
    *,
    research_id: UUID,
    run_id: UUID,
    question: str,
    started_at: datetime,
) -> ResearchState:
    """Build a running state. Both ids are generated by the caller."""
    if started_at.tzinfo is None:
        raise GraphStateError("started_at must be timezone-aware")
    state: ResearchState = {
        "schema_version": STATE_SCHEMA_VERSION,
        "research_id": str(research_id),
        "run_id": str(run_id),
        "question": question.strip(),
        "plan": None,
        "query_batches": [],
        "candidate_urls": [],
        "accepted_source_ids": [],
        "accepted_urls": [],
        "rejected_urls": [],
        "evidence": [],
        "coverage": None,
        "iteration": 0,
        "usage": empty_usage(),
        "warnings": [],
        "status": "running",
        "report": None,
        "error_code": None,
        "started_at": started_at.isoformat(),
        "iteration_progress": {"pages_indexed": 0, "chunk_ids": []},
    }
    return validate_state(state)


def empty_usage() -> UsageSnapshot:
    """Zero logical usage. Nested calls are added after they return."""
    return {
        "search_calls": 0,
        "llm_calls": 0,
        "pages_indexed": 0,
        "pages_failed": 0,
        "evaluation_calls": 0,
        "synthesis_calls": 0,
    }


def copy_usage(usage: UsageSnapshot) -> UsageSnapshot:
    """Copy logical counts so a charge cannot change the previous snapshot."""
    return {
        "search_calls": usage["search_calls"],
        "llm_calls": usage["llm_calls"],
        "pages_indexed": usage["pages_indexed"],
        "pages_failed": usage["pages_failed"],
        "evaluation_calls": usage["evaluation_calls"],
        "synthesis_calls": usage["synthesis_calls"],
    }


def snapshot_progress(state: ResearchState) -> ProgressSnapshot:
    """Copy the counts a later route compares against. Does not mutate state."""
    return {
        "pages_indexed": state["usage"]["pages_indexed"],
        "chunk_ids": [item["chunk_id"] for item in state["evidence"]],
    }


def graph_usage(state: ResearchState) -> GraphUsage:
    """External usage view. ``iterations`` is the discovery rounds started."""
    usage = state["usage"]
    return GraphUsage(
        iterations=state["iteration"],
        search_calls=usage["search_calls"],
        llm_calls=usage["llm_calls"],
        pages_indexed=usage["pages_indexed"],
        pages_failed=usage["pages_failed"],
    )


def validate_state(value: object) -> ResearchState:
    """Reject missing keys, bad versions, negative usage, and non-JSON values."""
    if not isinstance(value, dict):
        raise GraphStateError("state must be an object")
    _reject_non_json(value, "state")
    keys = set(value)
    expected = set(_STATE_KEYS)
    if keys != expected:
        missing = expected - keys
        unknown = keys - expected
        raise GraphStateError(
            f"state keys missing={sorted(missing)} unknown={sorted(unknown)}"
        )
    version = value["schema_version"]
    if isinstance(version, bool) or version != STATE_SCHEMA_VERSION:
        raise GraphStateError("unsupported state schema")
    research_id = _uuid_text(value["research_id"], "research_id")
    _uuid_text(value["run_id"], "run_id")
    question = _text(value["question"], "question", max_length=_MAX_QUESTION)
    if not question.strip():
        raise GraphStateError("question must not be empty")
    _validate_plan(value["plan"])
    _validate_batches(value["query_batches"])
    _validate_candidates(value["candidate_urls"])
    _validate_url_list(value["accepted_urls"], "accepted_urls")
    _validate_url_list(value["rejected_urls"], "rejected_urls")
    _validate_uuid_list(value["accepted_source_ids"], "accepted_source_ids")
    _validate_evidence(value["evidence"], research_id)
    _validate_coverage(value["coverage"])
    iteration = _non_negative_int(value["iteration"], "iteration")
    if iteration > _MAX_BATCHES:
        raise GraphStateError("iteration is outside the graph cap")
    _validate_usage(value["usage"])
    _validate_warnings(value["warnings"])
    _validate_progress(value["iteration_progress"])
    _validate_terminal(value["status"], value["report"], value["error_code"])
    _validate_started_at(value["started_at"])
    return cast(ResearchState, value)


def merge_update(state: ResearchState, update: Mapping[str, object]) -> ResearchState:
    """Deep-copy a replacement update. The input lists stay as they were."""
    current: dict[str, object] = dict(state)
    for key in update:
        if key not in current:
            raise GraphStateError(f"unknown state field {key}")
    current.update(update)
    try:
        encoded = json.dumps(current, allow_nan=False)
    except (TypeError, ValueError) as exc:
        raise GraphStateError("state is not JSON") from exc
    loaded: object = json.loads(encoded)
    return validate_state(loaded)


def mark_interrupted(state: ResearchState) -> ResearchState:
    """Record a cancelled run. A later step must not mark it completed."""
    return merge_update(
        state,
        {
            "status": "interrupted",
            "report": None,
            "error_code": "interrupted",
        },
    )


async def apply_update(
    state: ResearchState,
    work: Callable[[], Awaitable[Mapping[str, object]]],
) -> ResearchState:
    """Apply one node update. Cancellation leaves the previous state in place."""
    try:
        update = await work()
    except asyncio.CancelledError:
        raise
    return merge_update(state, update)


def _validate_plan(value: object) -> None:
    if value is None:
        return
    try:
        ResearchPlan.model_validate(value)
    except ValidationError:
        raise GraphStateError("plan is invalid") from None


def _validate_batches(value: object) -> None:
    batches = _list(value, "query_batches", max_length=_MAX_BATCHES)
    for batch in batches:
        queries = _list(batch, "query_batches", max_length=_MAX_QUERIES_PER_BATCH)
        for query in queries:
            text = _text(query, "query", max_length=QUERY_MAX_LENGTH)
            if not text.strip():
                raise GraphStateError("query must not be empty")


def _validate_candidates(value: object) -> None:
    items = _list(value, "candidate_urls", max_length=_MAX_CANDIDATES)
    for item in items:
        if not isinstance(item, dict):
            raise GraphStateError("candidate must be an object")
        url = _text(item.get("url"), "candidate url", max_length=2048)
        _normalized_url(url, "candidate url")
        _text(item.get("title"), "candidate title", max_length=_MAX_TITLE)
        if set(item) != {"url", "title"}:
            raise GraphStateError("candidate has unexpected fields")


def _validate_url_list(value: object, field_name: str) -> None:
    items = _list(value, field_name, max_length=_MAX_CANDIDATES)
    for item in items:
        _normalized_url(_text(item, field_name, max_length=2048), field_name)


def _validate_uuid_list(value: object, field_name: str) -> None:
    items = _list(value, field_name, max_length=_MAX_EVIDENCE)
    for item in items:
        _uuid_text(item, field_name)


def _validate_evidence(value: object, research_id: str) -> None:
    items = _list(value, "evidence", max_length=_MAX_EVIDENCE)
    for item in items:
        if not isinstance(item, dict):
            raise GraphStateError("evidence must be an object")
        if set(item) != {
            "chunk_id",
            "source_id",
            "research_id",
            "url",
            "page_number",
            "score",
            "excerpt",
        }:
            raise GraphStateError("evidence has unexpected fields")
        _uuid_text(item["chunk_id"], "chunk_id")
        _uuid_text(item["source_id"], "source_id")
        if _uuid_text(item["research_id"], "evidence research_id") != research_id:
            raise GraphStateError("evidence is outside the research scope")
        url = item["url"]
        if url is not None:
            _normalized_url(_text(url, "evidence url", max_length=2048), "evidence url")
        page = item["page_number"]
        if page is not None:
            number = _non_negative_int(page, "page_number")
            if number < 1:
                raise GraphStateError("page_number must be 1-based")
        score = item["score"]
        if isinstance(score, bool) or not isinstance(score, int | float):
            raise GraphStateError("score must be a number")
        if not math.isfinite(float(score)):
            raise GraphStateError("score must be finite")
        _text(item["excerpt"], "excerpt", max_length=MAX_STORED_EXCERPT)


def _validate_coverage(value: object) -> None:
    if value is None:
        return
    if not isinstance(value, dict):
        raise GraphStateError("coverage must be an object")
    if set(value) != {
        "sufficient",
        "covered_task_ids",
        "missing_task_ids",
        "gaps",
        "uncertainty",
    }:
        raise GraphStateError("coverage has unexpected fields")
    if not isinstance(value["sufficient"], bool):
        raise GraphStateError("coverage sufficient must be a boolean")
    for field_name in ("covered_task_ids", "missing_task_ids"):
        ids = _list(value[field_name], field_name, max_length=_MAX_TASK_IDS)
        for task_id in ids:
            _text(task_id, field_name, max_length=QUERY_MAX_LENGTH)
    gaps = _list(value["gaps"], "gaps", max_length=_MAX_TASK_IDS)
    for gap in gaps:
        _text(gap, "gaps", max_length=_MAX_COVERAGE_TEXT)
    _text(value["uncertainty"], "uncertainty", max_length=_MAX_COVERAGE_TEXT)


def _validate_usage(value: object) -> None:
    if not isinstance(value, dict):
        raise GraphStateError("usage must be an object")
    expected = {
        "search_calls",
        "llm_calls",
        "pages_indexed",
        "pages_failed",
        "evaluation_calls",
        "synthesis_calls",
    }
    if set(value) != expected:
        raise GraphStateError("usage has unexpected fields")
    for field_name in expected:
        _non_negative_int(value[field_name], field_name)


def _validate_warnings(value: object) -> None:
    warnings = _list(value, "warnings", max_length=_MAX_WARNINGS)
    for warning in warnings:
        text = _text(warning, "warning", max_length=_MAX_WARNING)
        if not text.isidentifier():
            raise GraphStateError("warning must be a code")


def _validate_progress(value: object) -> None:
    if not isinstance(value, dict):
        raise GraphStateError("iteration_progress must be an object")
    if set(value) != {"pages_indexed", "chunk_ids"}:
        raise GraphStateError("iteration_progress has unexpected fields")
    _non_negative_int(value["pages_indexed"], "iteration_progress.pages_indexed")
    chunk_ids = _list(value["chunk_ids"], "chunk_ids", max_length=_MAX_EVIDENCE)
    for chunk_id in chunk_ids:
        _uuid_text(chunk_id, "chunk_ids")


def _validate_terminal(status: object, report: object, error_code: object) -> None:
    if not isinstance(status, str):
        raise GraphStateError("status must be a string")
    if status == "running":
        if report is not None or error_code is not None:
            raise GraphStateError("a running state has no report or error")
        return
    if status in _FAILURE_STATUSES:
        if report is not None or not _error_code(error_code):
            raise GraphStateError("a failed state has an error and no report")
        return
    if status not in _REPORT_STATUSES:
        raise GraphStateError("unknown status")
    if error_code is not None or report is None:
        raise GraphStateError("a finished report has no error code")
    try:
        ResearchReport.model_validate(report)
    except ValidationError:
        raise GraphStateError("report is invalid") from None


def _validate_started_at(value: object) -> None:
    if not isinstance(value, str):
        raise GraphStateError("started_at must be a timestamp")
    try:
        started = datetime.fromisoformat(value)
    except ValueError:
        raise GraphStateError("started_at must be a timestamp") from None
    if started.tzinfo is None:
        raise GraphStateError("started_at must be timezone-aware")


def _error_code(value: object) -> bool:
    return (
        isinstance(value, str)
        and 0 < len(value) <= _MAX_WARNING
        and value.isidentifier()
    )


def _reject_non_json(value: object, path: str) -> None:
    if value is None or isinstance(value, str | bool):
        return
    if isinstance(value, int):
        return
    if isinstance(value, float):
        if not math.isfinite(value):
            raise GraphStateError(f"{path} is not finite")
        return
    if isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str):
                raise GraphStateError(f"{path} has a non-string key")
            _reject_non_json(item, f"{path}.{key}")
        return
    if isinstance(value, list):
        for index, item in enumerate(value):
            _reject_non_json(item, f"{path}[{index}]")
        return
    raise GraphStateError(f"{path} is not JSON")


def _list(value: object, field_name: str, *, max_length: int) -> list[object]:
    if not isinstance(value, list):
        raise GraphStateError(f"{field_name} must be a list")
    if len(value) > max_length:
        raise GraphStateError(f"{field_name} is too long")
    return value


def _text(value: object, field_name: str, *, max_length: int) -> str:
    if not isinstance(value, str):
        raise GraphStateError(f"{field_name} must be a string")
    if len(value) > max_length:
        raise GraphStateError(f"{field_name} is too long")
    return value


def _uuid_text(value: object, field_name: str) -> str:
    text = _text(value, field_name, max_length=36)
    try:
        parsed = UUID(text)
    except ValueError:
        raise GraphStateError(f"{field_name} must be a UUID") from None
    if str(parsed) != text:
        raise GraphStateError(f"{field_name} must be a canonical UUID")
    return text


def _normalized_url(value: str, field_name: str) -> None:
    if normalize_url(value) != value:
        raise GraphStateError(f"{field_name} must be a normalized URL")


def _non_negative_int(value: object, field_name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise GraphStateError(f"{field_name} must be a non-negative integer")
    return value
